#!/usr/bin/env python3
"""Cross-platform Muse Bot setup script (Windows PowerShell / macOS / Linux, zero Git Bash).

Usage:
    python tools/setup.py [--skip-sync] [--skip-web] [--home PATH]
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Optional, Sequence

REPO_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_CONFIG_YAML = """# Muse Bot starter configuration (auto-generated by tools/setup.py; never overwritten).
# Add models in the app (设置 → 模型 → 添加模型); keys are stored in <HOME>/.env (0600).

streaming:
  enabled: true
  cursor: ""

display:
  language: zh

agent:
  max_turns: 100

timezone: Asia/Shanghai

cron:
  wrap_response: false

mcp_servers:
  browser:
    command: npx
    args:
      - -y
      - "@playwright/mcp@0.0.83"
      - --no-webmcp
      - --cdp-endpoint
      - http://127.0.0.1:9333
    timeout: 120
    connect_timeout: 120
"""


def resolve_setup_home(repo_root: Path, explicit_home: Optional[str] = None) -> Path:
    """Resolve data home honoring explicit --home, MUSE_HOME, HERMES_HOME, or existing dir."""
    if explicit_home and explicit_home.strip():
        return Path(os.path.expanduser(os.path.expandvars(explicit_home.strip())))
    for env_key in ("MUSE_HOME", "HERMES_HOME"):
        val = os.environ.get(env_key, "").strip()
        if val:
            return Path(os.path.expanduser(os.path.expandvars(val)))
    muse_dir = repo_root / "muse-home"
    hermes_dir = repo_root / "hermes-home"
    if muse_dir.exists():
        return muse_dir
    if hermes_dir.exists():
        return hermes_dir
    return muse_dir


def ensure_default_config(home: Path) -> bool:
    """Create `<home>/config.yaml` with default `mcp_servers.browser` if absent.

    Returns True when a new starter config was written, False when preserved as-is.
    """
    created_home = not home.exists()
    home.mkdir(parents=True, exist_ok=True)
    if created_home and os.name == "posix":
        try:
            os.chmod(home, 0o700)
        except OSError:
            pass
    cfg_path = home / "config.yaml"
    if cfg_path.exists():
        return False
    cfg_path.write_text(DEFAULT_CONFIG_YAML, encoding="utf-8", newline="\n")
    return True


def _run_step(cmd: list[str], *, cwd: Path, label: str) -> None:
    print(f"==> {label}", flush=True)
    result = subprocess.run(cmd, cwd=str(cwd))
    if result.returncode != 0:
        raise RuntimeError(f"{label} failed with exit code {result.returncode}")


def run_setup(
    *,
    repo_root: Optional[Path] = None,
    home: Optional[str] = None,
    skip_sync: bool = False,
    skip_web: bool = False,
    python_version: Optional[str] = None,
) -> int:
    root = (repo_root or REPO_ROOT).resolve()
    target_home = resolve_setup_home(root, home)

    uv_bin = shutil.which("uv") if not skip_sync else None
    if not skip_sync and not uv_bin:
        print(
            "[stop] uv is missing. Install it from https://docs.astral.sh/uv/getting-started/installation/",
            file=sys.stderr,
        )
        return 1

    npm_bin = shutil.which("npm") if not skip_web else None
    if not skip_web and not npm_bin:
        print("[stop] Node.js / npm is missing. Install Node.js 18+ from https://nodejs.org", file=sys.stderr)
        return 1

    try:
        if not skip_sync:
            assert uv_bin is not None
            sync_cmd = [uv_bin, "sync", "--frozen", "--no-dev"]
            if python_version:
                sync_cmd.extend(["--python", python_version])
            _run_step(sync_cmd, cwd=root, label="Python environment (.venv via uv sync --frozen)")

        written = ensure_default_config(target_home)
        status = "created starter config.yaml with mcp_servers.browser" if written else "kept existing config.yaml"
        print(f"==> Data directory: {target_home} ({status})", flush=True)

        if not skip_web:
            assert npm_bin is not None
            web_dir = root / "web"
            if not (web_dir / "package.json").is_file():
                raise RuntimeError(f"Web directory missing package.json: {web_dir}")
            _run_step([npm_bin, "ci"], cwd=web_dir, label="Web dependencies (npm ci)")
            _run_step([npm_bin, "run", "build"], cwd=web_dir, label="Web app build (web/dist)")
    except RuntimeError as exc:
        print(f"[stop] {exc}", file=sys.stderr)
        return 1

    print("\nReady. Start Muse Bot:\n", flush=True)
    print("  uv run musebot serve", flush=True)
    print("\nThen open http://127.0.0.1:8766 (no pairing needed on this computer).", flush=True)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="setup.py",
        description="Set up Muse Bot on Windows, macOS, or Linux (uv .venv + config.yaml + web/dist).",
    )
    parser.add_argument("--home", default=None, help="Data directory for config, keys, chats, and muse.db")
    parser.add_argument("--python", dest="python_version", default=None, help="Optional Python version for uv sync")
    parser.add_argument("--skip-sync", action="store_true", help="Skip `uv sync --frozen --no-dev`")
    parser.add_argument("--skip-web", action="store_true", help="Skip building web/dist with npm")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    return run_setup(
        home=args.home,
        skip_sync=args.skip_sync,
        skip_web=args.skip_web,
        python_version=args.python_version,
    )


if __name__ == "__main__":
    raise SystemExit(main())
